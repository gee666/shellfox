export async function snapshot(page) {
  const result=await page.evaluate(()=>window.shellfox.getSnapshot());
  if(!result.ok)throw new Error(result.error.message);
  return result.value;
}
async function seedTerminal(context,line) {
  await expect.poll(async()=>{
    const current=await snapshot(context.page);
    return current.sessions.find(s=>s.title==='Parity project')?.tabs.at(-1)?.lifecycle;
  },{timeout:20000}).toBe('open');
  const state=await snapshot(context.page);
  const session=state.sessions.find(s=>s.title==='Parity project');
  const tab=session.tabs.at(-1);
  const script=`function global:prompt { 'PS parity> ' }; $Host.UI.RawUI.WindowTitle='Parity shell'; Clear-Host; Write-Output '${line}'; Write-Host 'ready' -ForegroundColor Green\r`;
  const result=await context.app.evaluate((_,input)=>Reflect.get(globalThis,'__shellfoxTest').service.writeTerminal(input),{tabId:tab.id,generation:tab.generation,data:script,userInitiated:true});
  if(!result.ok)throw new Error(result.error.message);
  await expect.poll(()=>context.app.evaluate((_,id)=>{
    const term=Reflect.get(globalThis,'__shellfoxTest').backend.entries.get(id)?.mirror.term;
    if(!term)return '';
    return Array.from({length:term.rows},(_,row)=>term.buffer.active.getLine(term.buffer.active.viewportY+row)?.translateToString(true)||'').join('\n');
  },tab.id)).toContain(line);
  await context.page.getByRole('button',{name:'New terminal',exact:true}).focus();
}
