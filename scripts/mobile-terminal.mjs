import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(resolve(root, 'package.json'));
const output = resolve(root, 'mobile/src/terminal/terminal-html.ts');
const result = await build({
  absWorkingDir: root, entryPoints: ['mobile/src/terminal/terminal-page.ts'], bundle: true,
  write: false, format: 'iife', platform: 'browser', target: ['es2020'], minify: true,
  legalComments: 'inline', sourcemap: false,
});
if (result.outputFiles.length !== 1) throw new Error('Expected one bundled terminal script.');
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const cssPath = resolve(dirname(require.resolve('@xterm/xterm/package.json')), 'css/xterm.css');
const css = await readFile(cssPath, 'utf8');
if (/@import|url\s*\(/i.test(css)) throw new Error('xterm CSS must not load external resources.');
const hash = createHash('sha256').update(script).digest('base64');
const policy = `default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; connect-src 'none'; img-src 'none'; font-src 'none'; media-src 'none'; object-src 'none'; frame-src 'none'; worker-src 'none'; base-uri 'none'; form-action 'none'`;
const html = `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${policy}"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"><style>${css}\nhtml,body,#terminal{margin:0;width:100%;height:100%;overflow:hidden;background:#111318}#terminal{box-sizing:border-box;padding:3px}.xterm{height:100%}.xterm-viewport{overscroll-behavior:contain}.xterm-helper-textarea{font-size:16px!important}</style></head><body><div id="terminal"></div><script>${script}</script></body></html>`;
const content = `// Generated by scripts/mobile-terminal.mjs. Do not edit. Includes xterm.js, addon-fit and their license notices.\nexport const TERMINAL_HTML = ${JSON.stringify(html)};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('Terminal HTML is stale. Run node scripts/mobile-terminal.mjs.');
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, content, 'utf8');
}
console.log(`Terminal HTML ${process.argv.includes('--check') ? 'verified' : 'generated'} (${Buffer.byteLength(html)} bytes).`);
