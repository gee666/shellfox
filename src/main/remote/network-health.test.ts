import { afterEach, expect, it, vi } from 'vitest';
import { FakeRemoteHelper, remoteFixture, signedHeaders } from './test-fixtures';
import type { RemoteEvent } from '../../shared/remote-contracts';
const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => { for (const cleanup of cleanups.splice(0).reverse()) await cleanup(); });
it('pushes recovery and degraded health without replacing the helper, backend listener, approvals or PTYs', async () => {
  const f = await remoteFixture(new Map<string, FakeRemoteHelper>(), 'host'); cleanups.push(f.dispose);
  const created = await f.create(); if (!created.ok) throw new Error('Session creation failed');
  const before = f.service.getSnapshot(); if (!before.ok) throw new Error('Snapshot failed');
  const proxy = f.helper.server?.address(), backend = f.helper.backendUrl, backendSecret = f.helper.secret, proxySecret = f.helper.proxySecret;
  const dispose = vi.spyOn(f.helper, 'dispose'), events: RemoteEvent[] = [];
  f.remote.subscribe(event => events.push(event));
  f.helper.emitStatus({ status: 'error', loginUrl: null, error: 'Tailscale control connection unavailable. Reconnecting automatically.' });
  expect(f.remote.getState()).toMatchObject({ ok: true, value: { enabled: true, status: 'error', loginUrl: null, error: expect.stringContaining('Reconnecting automatically') } });
  const route = '/v1/discover', body = '{}';
  const response = await fetch(backend + route, { method: 'POST', body, headers: signedHeaders(backendSecret, { id: 'same-owner', hostname: 'peer' }, route, body) });
  expect(await response.json()).toMatchObject({ ok: true, value: { service: 'shellfox' } });
  f.helper.emitStatus({ status: 'online', loginUrl: null, error: 'Tailscale relay or socket connectivity is degraded. Repair is retrying automatically.' });
  expect(f.remote.getState()).toMatchObject({ ok: true, value: { status: 'online', error: expect.stringContaining('degraded') } });
  f.helper.emitStatus({ status: 'online', loginUrl: null, error: null });
  expect(f.remote.getState()).toMatchObject({ ok: true, value: { status: 'online', error: null } });
  expect(events.filter(event => event.type === 'state').map(event => event.state.status)).toEqual(['error', 'online', 'online']);
  expect(f.helper.server?.address()).toEqual(proxy); expect(f.helper.backendUrl).toBe(backend);
  expect(f.helper.secret).toBe(backendSecret); expect(f.helper.proxySecret).toBe(proxySecret);
  expect(f.helper.commands.filter(command => command.method === 'start')).toHaveLength(1);
  expect(f.helper.commands.some(command => command.method === 'login')).toBe(false); expect(dispose).not.toHaveBeenCalled();
  const after = f.service.getSnapshot(); if (!after.ok) throw new Error('Snapshot failed');
  expect(after.value.sessions[0].tabs[0].generation).toBe(before.value.sessions[0].tabs[0].generation);
  expect(f.service.ownedTerminalCount()).toBe(1); expect(f.processes[0].kill).not.toHaveBeenCalled();
});
