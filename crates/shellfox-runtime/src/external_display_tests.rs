use super::*;
use ExternalStream::{Stderr, Stdout};
fn render(events: &[(ExternalStream, &[u8])]) -> (Vec<String>, String) {
    let mut display = Display::new(ExternalDisplayPolicy::LegacyAutomationV1);
    let writes = events
        .iter()
        .map(|(stream, bytes)| {
            String::from_utf8(display.data(*stream, bytes).into_owned()).unwrap()
        })
        .collect();
    (writes, String::from_utf8(display.finish()).unwrap())
}
#[test]
fn node_stringdecoder_oracles_keep_descriptor_state_and_final_stdout_stderr_flush_order() {
    assert_eq!(
        render(&[(Stdout, &[0xf0, 0x9f]), (Stderr, &[0x91, 0xa9])]),
        (vec!["".into(), "��".into()], "�".into())
    );
    assert_eq!(
        render(&[
            (Stdout, &[0xf0, 0x9f]),
            (Stderr, &[0xe2]),
            (Stdout, &[0x91, 0xa9]),
            (Stderr, &[0x82, 0xac])
        ]),
        (
            vec!["".into(), "".into(), "👩".into(), "€".into()],
            "".into()
        )
    );
    assert_eq!(
        render(&[(Stdout, &[0xf0, 0x9f]), (Stderr, &[0xe2, 0x82])]),
        (vec!["".into(), "".into()], "��".into())
    );
}
#[test]
fn newline_normalization_is_per_display_callback_not_a_cross_chunk_crlf_decoder() {
    assert_eq!(
        render(&[(Stdout, b"a\r"), (Stderr, b"\nb\n"), (Stdout, b"\nc\r\n")]),
        (
            vec!["a\r".into(), "\r\nb\r\n".into(), "\r\nc\r\n".into()],
            "".into()
        )
    );
    assert_eq!(
        render(&[(Stdout, b"l\r"), (Stdout, b"\nr")]),
        (vec!["l\r".into(), "\r\nr".into()], "".into())
    );
}
#[test]
fn malformed_prefixes_are_shape_buffered_like_node_not_eagerly_replaced_before_other_streams() {
    assert_eq!(
        render(&[(Stdout, &[0xed, 0xa0]), (Stderr, b"S"), (Stdout, &[0x80])]),
        (vec!["".into(), "S".into(), "���".into()], "".into())
    );
    assert_eq!(
        render(&[(Stdout, &[0xc0]), (Stderr, b"S"), (Stdout, &[0x80])]),
        (vec!["".into(), "S".into(), "��".into()], "".into())
    );
}
#[test]
fn all_byte_pairs_with_interleaved_stderr_match_the_actual_node_oracle_fingerprint() {
    // Generated by the fixed Node StringDecoder oracle; length prefixes keep
    // callback boundaries observable, not merely concatenated final content.
    fn add(hash: &mut u64, bytes: &[u8]) {
        for byte in [bytes.len() as u8, (bytes.len() >> 8) as u8]
            .iter()
            .chain(bytes)
        {
            *hash ^= u64::from(*byte);
            *hash = hash.wrapping_mul(0x100000001b3);
        }
    }
    let mut hash = 0xcbf29ce484222325;
    for a in 0..=255u8 {
        for b in 0..=255u8 {
            let mut display = Display::new(ExternalDisplayPolicy::LegacyAutomationV1);
            add(&mut hash, &display.data(Stdout, &[a]));
            add(&mut hash, &display.data(Stderr, b"S"));
            add(&mut hash, &display.data(Stdout, &[b]));
            add(&mut hash, &display.finish());
        }
    }
    assert_eq!(hash, 0x46966fdce61daa55);
}
#[test]
fn default_raw_policy_never_decodes_normalizes_or_flushes_synthetic_bytes() {
    let mut display = Display::new(ExternalDisplayPolicy::RawBytes);
    assert_eq!(display.data(Stdout, &[0xf0, 0x9f]).as_ref(), &[0xf0, 0x9f]);
    assert_eq!(display.data(Stderr, b"\n").as_ref(), b"\n");
    assert!(display.finish().is_empty());
}
