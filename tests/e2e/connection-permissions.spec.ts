import { expect, test } from '@playwright/test';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { remoteApps } from '../fixtures/remote-apps';
import { snapshot, value } from '../fixtures/electron';

test('request, reject, retry, allow, recursive remote folder creation and revoke work through the UI', async () => {
  test.setTimeout(180_000);
  const fixture = await remoteApps('connection-permissions');
  try {
    const host = await fixture.open('host'), client = await fixture.open('client');
    value(await host.page.evaluate(() => window.shellfoxRemote!.configure({ enabled: true, hostname: 'workstation' })));
    value(await client.page.evaluate(() => window.shellfoxRemote!.configure({ enabled: true, hostname: 'laptop' })));
    value(await host.page.evaluate(input => window.shellfox.createSession(input), { cwd: fixture.directory, title: 'Host only', requestId: randomUUID() }));
    await expect.poll(async () => (await fixture.state(client.page)).peers.some(peer => peer.id === 'workstation')).toBe(true);
    await client.page.getByRole('button', { name: 'Settings', exact: true }).click();
    await client.page.getByRole('tab', { name: 'Remote access', exact: true }).click();
    await client.page.getByRole('button', { name: 'Connect workstation', exact: true }).click();
    await expect.poll(async () => (await fixture.state(client.page)).peers.find(peer => peer.id === 'workstation')?.connection).toBe('awaiting-approval');
    await expect(client.page.getByText(/Waiting for approval/).first()).toBeVisible();
    const denied = await client.page.evaluate(() => window.shellfoxRemote!.request({ peerId: 'workstation', method: 'getSnapshot', payload: {} }));
    expect(denied.ok).toBe(false); await expect(client.page.getByRole('button', { name: 'Select session Host only' })).toHaveCount(0);
    await expect(host.page.getByText('laptop wants to connect')).toBeVisible();
    await host.page.getByRole('button', { name: 'Review', exact: true }).click();
    await expect(host.page.getByRole('tab', { name: 'Remote access', exact: true })).toHaveAttribute('aria-selected', 'true');
    await host.page.getByRole('button', { name: 'Reject laptop', exact: true }).click();
    await expect.poll(async () => (await fixture.state(client.page)).peers.find(peer => peer.id === 'workstation')?.connection).toBe('rejected');
    await expect(client.page.getByRole('button', { name: 'Request access to workstation again' })).toBeVisible();
    await expect.poll(async () => (await fixture.state(host.page)).pending.length).toBe(0);
    await client.page.getByRole('button', { name: 'Request access to workstation again' }).click();
    await expect(host.page.getByRole('button', { name: 'Approve laptop', exact: true })).toBeVisible();
    await host.page.getByRole('button', { name: 'Approve laptop', exact: true }).click();
    await expect.poll(async () => (await fixture.state(client.page)).peers.find(peer => peer.id === 'workstation')?.connection).toBe('connected');
    await expect(client.page.getByRole('button', { name: 'Select session Host only' })).toHaveCount(1);
    const connection = client.page.getByRole('button', { name: 'Disconnect workstation', exact: true });
    const heading = connection.locator('..').locator('..');
    const [iconBox, headingBox] = await Promise.all([connection.boundingBox(), heading.boundingBox()]);
    expect(iconBox).not.toBeNull(); expect(headingBox).not.toBeNull();
    if (iconBox && headingBox) expect(Math.abs(iconBox.y + iconBox.height / 2 - headingBox.y - headingBox.height / 2)).toBeLessThan(2);
    await client.page.getByRole('button', { name: 'New session', exact: true }).click();
    await expect(client.page.getByRole('menu', { exact: true })).toBeVisible();
    await client.page.getByRole('menuitem', { name: /workstation/ }).click();
    const input = client.page.getByRole('combobox', { name: 'Folder path', exact: true });
    await expect(input).toBeVisible(); await expect(client.page.getByRole('button', { name: 'Browse folders', exact: true })).toHaveCount(0);
    const folder = path.join(fixture.directory, 'new-parent', 'child');
    await input.fill(folder); await input.press('Enter');
    await expect(client.page.getByRole('alertdialog', { name: 'Create missing folder?' })).toBeVisible();
    expect(existsSync(folder)).toBe(false);
    await client.page.getByRole('button', { name: 'Keep editing', exact: true }).click();
    await expect(input).toHaveValue(folder); await expect(input).toBeFocused(); expect(existsSync(folder)).toBe(false);
    expect((await snapshot(host.page)).sessions).toHaveLength(1);
    await input.press('Enter'); await client.page.getByRole('button', { name: 'Create folder', exact: true }).click();
    await expect(client.page.getByRole('dialog', { name: 'New session', exact: true })).toHaveCount(0);
    expect(existsSync(folder)).toBe(true);
    await expect.poll(async () => (await snapshot(host.page)).sessions.length).toBe(2);
    expect((await snapshot(client.page)).sessions).toHaveLength(0);
    const owned = (await snapshot(host.page)).sessions.flatMap(session => session.tabs).map(tab => ({ id: tab.id, generation: tab.generation }));
    await host.page.getByRole('button', { name: 'Revoke laptop', exact: true }).click();
    await host.page.getByRole('button', { name: 'Confirm revoke laptop', exact: true }).click();
    await expect.poll(async () => (await fixture.state(client.page)).peers.find(peer => peer.id === 'workstation')?.connection).toBe('rejected');
    const revoked = await client.page.evaluate(() => window.shellfoxRemote!.request({ peerId: 'workstation', method: 'getSessionStats', payload: {} }));
    expect(revoked.ok).toBe(false);
    expect((await snapshot(host.page)).sessions.flatMap(session => session.tabs).map(tab => ({ id: tab.id, generation: tab.generation }))).toEqual(owned);
  } finally { await fixture.close(); }
});
